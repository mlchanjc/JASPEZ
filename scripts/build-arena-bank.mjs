const GROUP_CHOICES = {
  "n5-particles": ["は", "が", "に", "で", "を"],
  "n5-movement": ["に", "へ", "で", "を"],
  "n4-conditionals": ["と", "ば", "たら", "なら"],
  "n4-aux-verbs": ["ていく", "てくる", "てみる", "てしまう", "ておく"],
  "n4-appearance": ["そうだ", "ようだ", "らしい", "みたいだ"],
  "n3-cause-effect": ["おかげで", "せいで", "せいか", "ばかりに"],
  "n3-purpose": ["ために", "ように", "ことにしている", "ことになっている"],
  "n3-concession": ["のに", "くせに", "わりに", "といっても"],
  "n3-time-aspect": ["うちに", "たびに", "とたんに", "あいだに"],
};

const rows = [];
const seen = new Set();

function add(groupId, before, after, reading, zh, answer, tip) {
  assert.ok(GROUP_CHOICES[groupId], `Unknown groupId: ${groupId}`);
  assert.ok(GROUP_CHOICES[groupId].includes(answer), `Answer '${answer}' not in ${groupId}`);
  const full = `${before}${answer}${after}`;
  if (seen.has(full)) return;
  seen.add(full);
  rows.push([groupId, before, after, reading, zh, answer, tip]);
}

